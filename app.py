import pandas as pd
import psycopg
import streamlit as st

BATCH_SIZE = 10

st.set_page_config(page_title="Fake User Generator", layout="wide")


# a new connection per query, because the free database closes idle connections
def query(sql, params=()):
    with psycopg.connect(st.secrets["DATABASE_URL"]) as conn, conn.cursor() as cur:
        cur.execute(sql, params)
        columns = [col.name for col in cur.description]
        return pd.DataFrame(cur.fetchall(), columns=columns)


locales = query("SELECT code, name FROM locales ORDER BY name")

st.title("Fake User Generator")
st.caption("All data is generated by SQL functions in PostgreSQL. The same locale and seed always give the same users.")

col1, col2 = st.columns(2)
locale = col1.selectbox("Locale", locales["code"], format_func=dict(zip(locales["code"], locales["name"])).get)
seed = col2.number_input("Seed", min_value=0, value=42, step=1)

# a new locale or seed starts again from the first batch
if st.session_state.get("params") != (locale, seed):
    st.session_state.params = (locale, seed)
    st.session_state.batch = 0

users = query("SELECT * FROM faker_users(%s, %s, %s, %s)", (locale, seed, st.session_state.batch, BATCH_SIZE))
st.dataframe(users, hide_index=True)

if st.button("Next batch", type="primary"):
    st.session_state.batch += 1
    st.rerun()
